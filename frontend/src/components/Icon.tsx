// Filled when asked: only shapes that still read when solid.
const SOLID = new Set(["star", "favorite", "radio_button_checked", "stop", "play_arrow"]);

export default function Icon({ name, size = 16, fill, className = "", style, title, onClick }: {
  name: string;
  size?: number | string;
  fill?: boolean;
  className?: string;
  style?: CSSProperties;
  title?: string;
  onClick?: MouseEventHandler<SVGSVGElement>;
}) {
  const Glyph = ICONS[name] ?? Circle;
  const px = typeof size === "number" ? size : parseFloat(size) || 16;
  return (
    <Glyph
      aria-hidden={title ? undefined : true}
      aria-label={title}
      size={px}
      // about 1.4px on screen at any size
      strokeWidth={Math.min(2.4, Math.max(1.25, (1.4 * 24) / px))}
      fill={fill && SOLID.has(name) ? "currentColor" : "none"}
      className={`shrink-0 ${className}`}
      style={style}
      onClick={onClick}
    />
  );
}
